// Requires marked@15.0.12 installed outside the repository.
// NODE_PATH=/path/to/node_modules node scripts/render_report.cjs
const fs = require('fs');
const path = require('path');
const {createHash} = require('crypto');
const {marked} = require('marked');
const root = path.resolve(__dirname, '..');
const markdown = fs.readFileSync(path.join(root, '20261021SocialSecurity.md'), 'utf8');
const landing = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const sponsor = landing.match(/<aside class="sponsor-banner"[\s\S]*?<\/aside>/)[0];
const content = marked.parse(markdown).replace(/src="(output\/report_math\/[^"?]+\.svg)(?:\?[^"]*)?"/g,
  (_, file) => {
    const version = createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest('hex').slice(0, 12);
    return `src="${file}?v=${version}"`;
  }).replace(/<table>[\s\S]*?<\/table>/g,
  table => `<div class="table-wrap" tabindex="0" role="region" aria-label="Report table">${table}</div>`);
fs.writeFileSync(path.join(root, 'report.html'), `<!doctype html>
<!-- Generated by scripts/render_report.cjs from 20261021SocialSecurity.md. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Social Security Investment — Report</title>
<link rel="stylesheet" href="web/style.css">
<link rel="stylesheet" href="web/report.css">
</head>
<body><main>
${sponsor}
<nav aria-label="Site navigation"><a href="index.html">Home</a><a href="web/index.html">Calculator</a><a href="https://github.com/TheBrookhavenGroup/ssa/blob/main/20261021SocialSecurity.md">Report source on GitHub</a></nav>
<article>
${content}
</article>
<footer><p>Copyright © 2026 The Brookhaven Group, LLC.</p></footer>
</main></body></html>
`);
console.log('Generated report.html');
